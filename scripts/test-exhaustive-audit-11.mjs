import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const checks = [];
const assert = (condition, name, details = '') => checks.push({ ok: Boolean(condition), name, details });

const schema = read('server/db/schema.ts');
const academic = read('server/services/academicContext.ts');
const authMiddleware = read('server/authMiddleware.ts');
const authRoutes = read('server/authRoutes.ts');
const paymentService = read('server/services/paymentService.ts');
const paymentRoutes = read('server/paymentRoutes.ts');
const studentProfile = read('server/services/studentProfile.ts');
const accessService = read('server/services/accessService.ts');
const pricing = read('src/components/PricingModal.tsx');
const upgrade = read('src/components/UpgradeModal.tsx');
const setup = read('LAUNCH_SETUP.md');
const metadata = JSON.parse(read('metadata.json'));

assert(schema.includes('expiresAt: timestamp("expires_at")'), 'Run expiry is persisted in schema.');
assert(fs.existsSync(path.join(root, 'server/db/migrations/0007_exhaustive_hardening.sql')), 'Audit 11 migration exists.');
assert(fs.existsSync(path.join(root, 'server/db/migrations/0008_exhaustive_integrity.sql')), 'Exhaustive integrity migration exists.');
assert(academic.includes("timeZone: 'Africa/Cairo'"), 'Academic term detection uses Cairo time zone.');
assert(authMiddleware.includes('if (!pool) return null;'), 'Protected auth fails closed when the DB is unavailable.');
assert(!authMiddleware.includes('const role = user.role ||'), 'Provider-supplied role is not trusted for authorization.');
assert(authMiddleware.includes("profile?.role === 'ADMIN'"), 'Admin role is sourced from the application profile.');
assert(authRoutes.includes('Invalid or expired verification code.'), 'Verification errors are normalized.');
assert(authRoutes.includes('emailVerified !== true') || authRoutes.includes('!dbUser.rows.length || !dbUser.rows[0].emailVerified'), 'Verification requires real Neon Auth verified state.');
assert(!paymentService.includes('export const PRICING'), 'Runtime payment prices are not hard-coded in service logic.');
assert(paymentService.includes('getProducts(includeDisabled = true)'), 'Products are database-backed.');
assert(paymentService.includes('resolvePurchaseContext'), 'Purchase term/year is server authoritative.');
assert(paymentRoutes.includes('getPaymentMethods(false)'), 'Public payment methods are filtered server-side.');
assert(paymentRoutes.includes('getProducts(false)'), 'Public products are filtered server-side.');
assert(studentProfile.includes('RUN_TTL_MS = 2 * 60 * 60 * 1000'), 'Run sessions have bounded lifetime.');
assert(studentProfile.includes('paidAccess'), 'Paid run start re-checks entitlement inside the transaction.');
assert(studentProfile.includes('A successful generated schedule result is required'), 'Run completion requires a persisted successful result.');
assert(accessService.includes('gt(runSessions.expiresAt, new Date())'), 'Expired free runs are normalized before access state is shown.');
assert(accessService.includes('freeRunStatus,') && !accessService.includes('freeRunStatus: student.freeRunStatus'), 'Normalized free-run status is returned to callers.');
assert(!pricing.includes('89 EGP</div>') && !pricing.includes('199 EGP</div>'), 'Pricing modal reads amounts dynamically.');
assert(!upgrade.includes('|| 89') && !upgrade.includes('|| 199'), 'Upgrade modal has no stale hard-coded price fallbacks.');
assert(paymentRoutes.includes("typeof enabled !== 'boolean'"), 'Admin payment/product enabled flags require actual booleans.');
assert(paymentRoutes.includes('set: { name: productName'), 'Admin product updates persist product-name changes.');
assert(paymentRoutes.includes('sendPaymentError(res, e)'), 'Admin product errors use the shared payment error response.');
const schedule = read('server/services/scheduleService.ts');
assert(schedule.includes('run.academic_year') && schedule.includes('run.term') && schedule.includes('INSERT INTO saved_schedules'), 'Saved schedules retain the academic context captured by their run.');
assert(schedule.includes('run.expires_at') && schedule.includes('getTime() <= Date.now()'), 'Saved schedule writes reject expired run sessions.');
assert(studentProfile.includes("'SCHEDULE_RUN_COMPLETED'"), 'Run completion audit event is not mislabeled as free-run completion.');
const config = read('server/config.ts');
assert(config.includes('Expected a boolean value'), 'Invalid boolean environment values fail fast.');
assert(config.includes("nodeEnv !== 'production'"), 'Vite external host allowance defaults off in production.');
assert(setup.includes('server verifies that the run produced a persisted valid schedule result'), 'Launch docs match run consumption behavior.');
assert(metadata.name === 'Gadwal', 'Metadata identifies the product correctly.');
assert(!fs.existsSync(path.join(root, 'patch.cjs')), 'One-off patch scripts are removed from the shipped project.');
assert(!fs.existsSync(path.join(root, 'filelist.txt')), 'Generated file list is removed from the shipped project.');

const failures = checks.filter((c) => !c.ok);
for (const check of checks) console.log(`${check.ok ? 'PASS' : 'FAIL'} — ${check.name}${check.details ? ` — ${check.details}` : ''}`);
if (failures.length) process.exit(1);
console.log(`EXHAUSTIVE AUDIT 11 CONTRACT: ${checks.length}/${checks.length} passed`);
