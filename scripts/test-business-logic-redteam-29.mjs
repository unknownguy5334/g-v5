import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[]; const ok=(n,c)=>checks.push([n,!!c]);
const student=read('server/services/studentProfile.ts');
const optimizer=read('server/optimizerRoutes.ts');
const schedule=read('server/services/scheduleService.ts');
const schema=read('server/db/schema.ts');
const migration=read('server/db/migrations/0016_business_logic_integrity.sql');
const journal=JSON.parse(read('server/db/migrations/meta/_journal.json'));
const acct=read('server/services/accountService.ts');
const payment=read('server/services/paymentService.ts');
ok('full-run result token is server generated', /randomBytes\(32\)\.toString\('base64url'\)/.test(optimizer) && /resultIntegrityToken/.test(optimizer));
ok('run stores only token hash', /resultTokenHash/.test(schema) && /createHash\(.*resultIntegrityToken/.test(optimizer));
ok('save requires run token', /resultIntegrityToken/.test(schedule) && /timingSafeEqual/.test(schedule));
ok('token check is ownership and active-run scoped', /eq\(runSessions\.studentId, user.id\)/.test(optimizer) && /eq\(runSessions\.status, 'IN_PROGRESS'\)/.test(optimizer));
ok('completion clears consumed token', /result_token_hash=NULL/.test(student));
ok('expired/stale runs clear consumed token', /result_token_hash=NULL/.test(student));
ok('business integrity migration present', /result_token_hash/.test(migration));
ok('journal includes 0016', journal.entries.at(-1)?.tag==='0016_business_logic_integrity' && journal.entries.at(-1)?.idx===16);
ok('account duplicate replacement is ownership scoped', /savedCourses\.studentId, studentId/.test(acct));
ok('payment state transitions remain pending-only', /payment_status='PENDING'/.test(payment));
for(const [n,c] of checks) console.log(`${c?'PASS':'FAIL'} — ${n}`);
const failed=checks.filter(([,c])=>!c); if(failed.length) process.exit(1); console.log(`Business Logic Domain 29 gate: ${checks.length}/${checks.length} passed`);
