import fs from 'fs';
import assert from 'assert';
const read = (p) => fs.readFileSync(p, 'utf8');
const server = read('server.ts');
const upstream = read('server/upstream.ts');
const db = read('server/db.ts');
const authRoutes = read('server/authRoutes.ts');
const authMw = read('server/authMiddleware.ts');
const profile = read('server/profileRoutes.ts');
const payment = read('server/paymentRoutes.ts');
const client = read('src/services/resilientFetch.ts');
const authClient = read('src/services/authClient.ts');
const upgrade = read('src/components/UpgradeModal.tsx');
const payments = read('src/components/PaymentHistoryModal.tsx');
const admin = read('src/AdminApp.tsx');
const main = read('src/main.tsx');
const app = read('src/App.tsx');
const ocr = read('server/ocrModelFallback.ts');
const contract = read('src/utils/ocrApiContract.ts');
let n = 0;
const check = (name, cond) => { n++; assert.ok(cond, name); };
check('server upstream fetches are time-bounded', upstream.includes('timeoutMs') && upstream.includes('AbortController'));
check('Neon auth outbound calls use timeout wrapper', authRoutes.includes('fetchWithTimeout') && authMw.includes('fetchWithTimeout'));
check('Gemini OCR calls use bounded retry timeout', ocr.includes('timeoutMs: 35_000') && contract.includes('generateWithTimeout'));
check('database connection has connection timeout', db.includes('connectionTimeoutMillis: 8000'));
check('database startup has bounded retries', db.includes('waitForDbReady') && server.includes('waitForDbReady({ attempts: 3'));
check('global request error middleware exists', server.includes('Final catch-all error middleware'));
check('unhandled promise rejection is logged', server.includes("process.on('unhandledRejection'"));
check('React top-level error boundary exists', main.includes('<ErrorBoundary>') && main.includes('components/ErrorBoundary'));
check('frontend network timeout helper exists', client.includes('NetworkTimeoutError') && client.includes('timeoutMs'));
check('auth client uses resilient fetch', authClient.includes('fetchJson'));
check('payment upgrade flow reports option-loading errors', upgrade.includes('Payment options could not be loaded'));
check('payment submission is bounded and retryable by user', upgrade.includes('timeoutMs: 20_000'));
check('payment history exposes request errors', payments.includes('setError'));
check('admin requests are time-bounded', admin.includes('fetchJson') && admin.includes('timeoutMs: 10_000'));
check('initial saved-data sync reports failures', app.includes('Could not load saved courses') && app.includes('Could not load saved schedules'));
check('OCR client already has a shared explicit timeout', app.includes('handleRunOptimizer') && read('src/components/StepAddCourses.tsx').includes('OCR_CLIENT_TIMEOUT_MS'));
check('OCR rate limits are surfaced distinctly', server.includes('isRateLimit') && server.includes('UPSTREAM_BUSY'));
check('profile endpoint catches failures', profile.includes('PROFILE_UNAVAILABLE'));
check('payment pricing endpoint catches failures', payment.includes('PRICING_UNAVAILABLE'));
console.log(`Resilience Audit 4 verification contract: ${n}/${n} passed`);
